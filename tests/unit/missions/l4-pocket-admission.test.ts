import { expect, test, vi } from 'vitest';
import { l4, l4Pockets } from '../../../src/data/l4';
import { LevelFourWar } from '../../../src/sim/missions/LevelFourWar';
import type { L4State } from '../../../src/sim/missions/types';
import type { EntitySnapshot } from '../../../src/sim/world/types';

test.each(['high', 'low'] as const)('L4 %s pockets retain their whole authored quota across full-cap retries and checkpoints', tier => {
  const quota = tier === 'low' ? 3 : 6;
  const player = { id: 1, transform: { x: -23, z: 0 } } as EntitySnapshot;
  const soldiers = [11, 12, 13].map(id => ({ id, transform: { x: 0, z: 0 }, civilian: { ally: {} } } as EntitySnapshot));
  const state = { phase: 'collapse', alphaIds: Array(l4.alphas.count[tier]).fill(1), pendingDoor: [], pockets: [0], hmgIds: [], director: {} } as unknown as L4State;
  const ai = { director: { tier, offscreen: () => true, reserved: 0 }, rush: vi.fn() };
  const mission = { state: { l4: state }, world: { tick: 200, entities: { get: () => player, iterate: () => [] }, infected: ai } };
  let room = 0, next = 100;
  const emerge = vi.fn<(point: unknown, push: boolean, headroom: number, reserved: boolean) => number>(() => room-- > 0 ? next++ : 0);
  const war = Object.assign(Object.create(LevelFourWar.prototype), { mission, liveSoldiers: () => soldiers, inGap: () => false, emerge }) as { emergeCollapse(): void; reserveSlots(): void };
  war.reserveSlots(); expect(ai.director.reserved).toBe(quota);
  war.emergeCollapse(); expect(state.pockets).toEqual([0]); expect(state.pocketSpawned?.[0]).toBe(0);
  const originalPost = soldiers[0].civilian!.ally!.post;
  room = 1; war.emergeCollapse();
  expect(state.pockets).toEqual([0]); expect(state.pocketSpawned?.[0]).toBe(1); expect(ai.director.reserved).toBe(quota - 1);
  expect(soldiers[0].civilian!.ally!.post).toBe(originalPost);
  mission.state.l4 = structuredClone(state);
  room = quota - 1; war.emergeCollapse();
  expect(mission.state.l4.pockets).toEqual([]); expect(mission.state.l4.pocketSpawned?.[0]).toBe(quota);
  expect(ai.director.reserved).toBe(0); expect(ai.rush).toHaveBeenCalledTimes(quota);
  expect(emerge.mock.calls.every(c => c[1] === false && c[2] === 0 && c[3] === true)).toBe(true);
  expect(ai.rush.mock.calls.map(c => c[0])).toEqual(Array.from({ length: quota }, (_, i) => 100 + i));
  expect(ai.rush.mock.calls[0][1]).toEqual({ x: l4Pockets[0].at[0][0], z: l4Pockets[0].at[0][1] });
  expect(soldiers[0].civilian!.ally!.post).toBe(originalPost);
});
