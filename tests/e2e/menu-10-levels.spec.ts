import { mkdirSync } from 'node:fs';
import { test, expect, boot } from './fixtures';
import { menuUrl } from './ui-helpers';
import { preset } from '../../src/sim/progression/Campaign';
import type { Game } from '../../src/Game';

for (const quality of ['high', 'low'] as const) test(`ten level menu ${quality} @menu-10-levels`, async ({ page }, info) => {
  test.setTimeout(180_000);
  if (info.project.name === 'chromium') await page.setViewportSize({ width: 1280, height: 720 });
  await boot(page, `${menuUrl.replace('quality=high', `quality=${quality}`)}&scenelab=1`);
  await page.evaluate(quality => window.__SS__!.settings.set({ quality }), quality);
  expect(await page.evaluate(() => window.__SS__!.getState().render.quality)).toBe(quality);
  await expect(page.getByTestId('continue-game')).toHaveCount(0);
  await expect(page.getByTestId('title-levels')).toHaveCount(0);
  await expect(page.getByTestId('menu-title').getByRole('button')).toHaveCount(3);
  const titleBounds = await page.getByTestId('menu-title').getByRole('button').evaluateAll(buttons => buttons.map(b => { const r = b.getBoundingClientRect(); return { top: r.top, bottom: r.bottom }; }));
  for (const bounds of titleBounds) { expect(bounds.top).toBeGreaterThanOrEqual(0); expect(bounds.bottom).toBeLessThanOrEqual(page.viewportSize()!.height); }
  const dir = 'test-results/menu-10-levels'; mkdirSync(dir, { recursive: true });
  await page.screenshot({ path: `${dir}/${info.project.name}-${quality}-title.png` });
  await page.getByTestId('start-game').click();
  await expect(page.getByTestId('menu-character')).toBeVisible();
  await page.getByTestId('character-female').click();
  await expect(page.locator('[data-testid^="level-L"]')).toHaveCount(10);
  await expect(page.getByTestId('level-L1')).toBeFocused();
  await page.getByTestId('level-L10').focus();
  await expect(page.getByTestId('level-L10')).toHaveAttribute('aria-disabled', 'true');
  await expect(page.getByRole('status').filter({ hasText: 'Complete Level 9 first' })).toBeVisible();
  await page.keyboard.press('Enter');
  await expect(page.getByTestId('menu-levels')).toBeVisible();
  await page.keyboard.press('Shift+Tab');
  await expect(page.getByTestId('level-L9')).toBeFocused();
  await page.getByTestId('levels-back').click();
  await expect(page.getByTestId('menu-character')).toBeVisible();
  const save = preset('L10-default'); save.settings.quality = quality;
  await page.evaluate(save => {
    window.__SS__!.campaign.restore(save); window.__SS__!.campaign.save();
    window.__SS__!.campaign.menu();
  }, save);
  await page.getByTestId('start-game').click();
  await expect(page.getByTestId('level-L10')).toBeFocused();
  await expect(page.getByTestId('level-L10')).toHaveClass(/is-recommended/);
  await expect(page.getByTestId('level-L10')).toHaveText('L10 · The Cure');
  await expect(page.getByTestId('level-resume-L10')).toHaveCount(0);
  await page.screenshot({ path: `${dir}/${info.project.name}-${quality}-levels.png` });
  const box = (await page.getByTestId('levels-back').boundingBox())!;
  expect(box.y + box.height).toBeLessThanOrEqual(page.viewportSize()!.height);
  await page.getByTestId('levels-back').click();
  await expect(page.getByTestId('menu-title')).toBeVisible();
  await page.getByTestId('start-game').click();
  await page.getByTestId('level-L10').click();
  await expect(page.getByTestId('pause-button')).toBeVisible({ timeout: 120_000 });
  await page.evaluate(() => window.__SS__!.screenshotReady());
  await page.evaluate(async () => {
    const game = (window.__SCENE__ as unknown as { game: Game }).game;
    window.__SS__!.pause();
    game.world.missions!.loadCheckpoint('cure-residential');
    await window.__SS__!.step(1);
    game.saveCampaign(); game.ui.show('title');
  });
  await page.getByTestId('start-game').click();
  await expect(page.getByTestId('level-resume-L10')).toBeVisible();
  await expect(page.getByTestId('level-restart-L10')).toBeVisible();
  await page.getByTestId('level-L10').click();
  await expect(page.getByTestId('pause-button')).toBeVisible({ timeout: 120_000 });
  await page.evaluate(() => window.__SS__!.screenshotReady());
  expect(await page.evaluate(() => (window.__SCENE__ as unknown as { game: Game }).game.world.missions!.state.checkpoint)).toBe('cure-residential');
  expect(await page.evaluate(() => window.__SS__!.campaign.state()!.cureResume)).toBeDefined();
  await page.evaluate(() => (window.__SCENE__ as unknown as { game: Game }).game.ui.show('title'));
  await page.getByTestId('start-game').click();
  await page.getByTestId('level-restart-L10').click();
  await expect(page.getByTestId('pause-button')).toBeVisible({ timeout: 120_000 });
  expect(await page.evaluate(() => (window.__SCENE__ as unknown as { game: Game }).game.world.missions!.state.checkpoint)).toBe('cure-crash');
});

test('L9 saved crossing row resumes and can restart @menu-10-levels', async ({ page }) => {
  test.setTimeout(180_000);
  await boot(page, `${menuUrl}&scenelab=1`);
  const save = preset('L8-default'); save.completedLevels = 8; save.unlockedLevel = 9;
  await page.evaluate(async save => {
    const game = (window.__SCENE__ as unknown as { game: Game }).game;
    await game.continueCampaign(save, 9);
    window.__SS__!.pause();
    const carId = game.world.missions!.l9!.state.carId;
    game.world.vehicles!.cars.get(carId)!.physics.body.setTranslation({ x: 100, y: 1, z: 0 }, true);
    await window.__SS__!.step(1);
    game.saveCampaign(); game.ui.show('title');
  }, save);
  expect(await page.evaluate(() => window.__SS__!.campaign.state()!.l9Crash!.vehicle.transform.x)).toBeCloseTo(100, 0);
  await page.getByTestId('start-game').click();
  await expect(page.getByTestId('level-resume-L9')).toBeVisible();
  await expect(page.getByTestId('level-L9')).toBeFocused();
  await page.getByTestId('level-L9').click();
  await expect(page.getByTestId('pause-button')).toBeVisible({ timeout: 120_000 });
  await page.evaluate(() => window.__SS__!.screenshotReady());
  expect(await page.evaluate(() => window.__SS__!.campaign.state()!.l9Crash!.vehicle.transform.x)).toBeCloseTo(100, 0);
  await page.evaluate(() => (window.__SCENE__ as unknown as { game: Game }).game.ui.show('title'));
  await page.getByTestId('start-game').click();
  await page.getByTestId('level-restart-L9').click();
  await expect(page.getByTestId('pause-button')).toBeVisible({ timeout: 120_000 });
  expect(await page.evaluate(() => (window.__SCENE__ as unknown as { game: Game }).game.world.entities.get((window.__SCENE__ as unknown as { game: Game }).game.world.missions!.l9!.state.carId)!.transform.x)).toBeLessThan(50);
});
