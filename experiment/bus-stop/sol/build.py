def roof(name,x0,x1,mat,thick=.045,lift=0):
    seg=40;verts=[]
    for x in [x0,x1]:
        for layer in [0,1]:
            for i in range(seg+1):
                y=-.87+1.74*i/seg;z=2.68+.43*(1-(y/.87)**2)-layer*thick+lift
                verts.append((x,y,z))
    stride=seg+1;faces=[]
    for i in range(seg):
        faces += [(i,i+1,2*stride+i+1,2*stride+i),(stride+i,3*stride+i,3*stride+i+1,stride+i+1), (i,stride+i,stride+i+1,i+1),(2*stride+i,2*stride+i+1,3*stride+i+1,3*stride+i)]
    faces +=[(0,2*stride,3*stride,stride),(seg,stride+seg,3*stride+seg,2*stride+seg)]
    me=bpy.data.meshes.new(name);me.from_pydata(verts,[],faces);me.update();uv=me.uv_layers.new()
    for p in me.polygons:
        for li in p.loop_indices:
            co=me.vertices[me.loops[li].vertex_index].co;uv.data[li].uv=((co.x-x0)/(x1-x0),(co.y+.87)/1.74)
    return finish(bpy.data.objects.new(name,me),mat,'barrel_canopy',bevel=.009,segs=2)
