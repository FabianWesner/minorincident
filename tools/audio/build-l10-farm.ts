/** Original MIT scare hits + heartbeat; licensed score aliases keep the source's bytes and attribution. */
import { copyFileSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { audioCues, categoryDuration } from '../../src/data/audioCues';
import { wave } from '../../src/audio/synthesis';
import { synthesizeL10Farm } from './l10-farm-synthesis';
const rate = 48000, bank = 'music-L10-fx', pcm = new Float32Array(Math.ceil(categoryDuration(bank) * rate));
for (const cue of Object.values(audioCues).filter(c => c.category === bank)) pcm.set(synthesizeL10Farm(cue, rate), Math.round(cue.offset * rate));
mkdirSync('.cache/audio', { recursive: true });
writeFileSync('.cache/audio/l10-fx.wav', wave([pcm], rate));
for (const ext of ['webm', 'm4a']) {
  const codec = ext === 'webm' ? ['-c:a', 'libopus', '-b:a', '64k'] : ['-c:a', 'aac', '-b:a', '64k'];
  const r = spawnSync('ffmpeg', ['-v', 'error', '-y', '-i', '.cache/audio/l10-fx.wav', ...codec, `public/assets/audio/${bank}.${ext}`]);
  if (r.status) throw Error(r.stderr.toString());
  for (const [dest, source] of Object.entries({ 'calm-L10': 'tension-L5', 'tension-L10': 'calm-L6', 'combat-L10': 'tension-L5' })) copyFileSync(`public/assets/audio/score-${source}.${ext}`, `public/assets/audio/score-${dest}.${ext}`);
}
const path = 'assets/audio/imports.json', imports = JSON.parse(readFileSync(path, 'utf8'));
imports.streams['calm-L10'] = { ...imports.streams['tension-L5'] };
imports.streams['tension-L10'] = { ...imports.streams['calm-L6'] };
imports.streams['combat-L10'] = { ...imports.streams['tension-L5'] };
writeFileSync(path, JSON.stringify(imports, null, 2) + '\n');
console.log('L10 score aliases and original scare bank built');

const licenseRows = ['## L10 farm soundtrack', '',
  'Original scare hits and heartbeat: Minor Incident contributors, MIT; generated by `tools/audio/build-l10-farm.ts`. No third-party samples or melody.', '',
  '"Zombie Hoodoo", "Static Motion", and "Metalmania" — Kevin MacLeod (incompetech.com), [CC BY 4.0](https://creativecommons.org/licenses/by/4.0/). Existing approved recordings are reused unchanged. Source evidence: `docs/licenses/audio/zombie-hoodoo.json`, `static-motion.json`, `metalmania.json`.', '',
  '| File | Recording / license | SHA256 |', '| --- | --- | --- |'];
for (const [stem, title] of Object.entries({ 'calm-L10': 'Zombie Hoodoo / CC BY 4.0', 'tension-L10': 'Static Motion / CC BY 4.0', 'combat-L10': 'Zombie Hoodoo / CC BY 4.0' })) for (const ext of ['webm', 'm4a']) {
  const name = `score-${stem}.${ext}`;
  licenseRows.push(`| ${name} | ${title} | ${createHash('sha256').update(readFileSync(`public/assets/audio/${name}`)).digest('hex')} |`);
}
for (const ext of ['webm', 'm4a']) {
  const name = `music-L10-fx.${ext}`;
  licenseRows.push(`| ${name} | Original synthesis / MIT | ${createHash('sha256').update(readFileSync(`public/assets/audio/${name}`)).digest('hex')} |`);
}
for (const file of ['assets/audio/LICENSES.md', 'public/assets/audio/LICENSES.md']) writeFileSync(file, readFileSync(file, 'utf8').split('## L10 farm soundtrack')[0].trimEnd() + '\n\n' + licenseRows.join('\n') + '\n');
