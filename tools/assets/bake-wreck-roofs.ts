import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { Matrix4, Vector3 } from 'three';
import manifest from '../../src/assets/manifest.json';
import { variantPath } from '../../src/assets/types';
import { assetIO } from './io';

/** Actual upward vehicle surfaces, separate from the intentionally 1.65 m clipped crowd collision boxes. */
const io = await assetIO();
const roofs: Record<string, { source: string; hash: string; positions: number[]; indices: number[] }> = {};
for (const def of manifest.filter(d => d.category === 'vehicle')) for (const decay of ['wrecked', 'burned']) {
  const source = variantPath(def.glb, decay);
  if (!existsSync(source)) continue;
  const doc = await io.read(source), triangles: number[][] = [];
  const a = new Vector3(), b = new Vector3(), c = new Vector3(), normal = new Vector3(), edge = new Vector3();
  for (const node of doc.getRoot().listNodes()) {
    if (node.getName().startsWith('stump_') || node.getExtras().hidden) continue;
    const matrix = new Matrix4().fromArray(node.getWorldMatrix());
    for (const primitive of node.getMesh()?.listPrimitives() ?? []) {
      const positions = primitive.getAttribute('POSITION'); if (!positions) continue;
      const indices = primitive.getIndices(), values: number[] = [];
      for (let i = 0; i < (indices?.getCount() ?? positions.getCount()); i += 3) {
        for (const [j, point] of [a, b, c].entries()) { positions.getElement(indices ? indices.getScalar(i + j) : i + j, values); point.fromArray(values).applyMatrix4(matrix); }
        normal.subVectors(b, a).cross(edge.subVectors(c, a));
        if (normal.lengthSq() < 1e-10 || normal.normalize().y < .5 || Math.max(a.y, b.y, c.y) < .45) continue;
        triangles.push([...a.toArray(), ...b.toArray(), ...c.toArray()].map(v => +v.toFixed(4)));
      }
    }
  }
  // Interior floors/seats are hidden below the roof. Retain exposed upward faces, including broken/stepped roof edges.
  const topAt = (x: number, z: number) => {
    let top = 0;
    for (const t of triangles) {
      if (x < Math.min(t[0], t[3], t[6]) || x > Math.max(t[0], t[3], t[6]) || z < Math.min(t[2], t[5], t[8]) || z > Math.max(t[2], t[5], t[8])) continue;
      const den = (t[5] - t[8]) * (t[0] - t[6]) + (t[6] - t[3]) * (t[2] - t[8]);
      if (Math.abs(den) < 1e-10) continue;
      const u = ((t[5] - t[8]) * (x - t[6]) + (t[6] - t[3]) * (z - t[8])) / den;
      const v = ((t[8] - t[2]) * (x - t[6]) + (t[0] - t[6]) * (z - t[8])) / den;
      if (u >= -1e-5 && v >= -1e-5 && u + v <= 1.00001) top = Math.max(top, u * t[1] + v * t[4] + (1 - u - v) * t[7]);
    }
    return top;
  };
  const positions: number[] = [], indices: number[] = [], vertices = new Map<string, number>();
  for (const t of triangles) {
    const samples = [t.slice(0, 3), t.slice(3, 6), t.slice(6, 9), [0, 1, 2].map(i => (t[i] + t[i + 3] + t[i + 6]) / 3)];
    if (samples.every(p => topAt(p[0], p[2]) > p[1] + .005)) continue;
    for (let i = 0; i < 9; i += 3) {
      const vertex = t.slice(i, i + 3), key = vertex.join(',');
      if (!vertices.has(key)) { vertices.set(key, positions.length / 3); positions.push(...vertex); }
      indices.push(vertices.get(key)!);
    }
  }
  roofs[`${def.id}:${decay}`] = { source, hash: createHash('sha256').update(readFileSync(source)).digest('hex'), positions, indices };
}
writeFileSync('src/assets/wreckRoofs.ts', '// Generated by tools/assets/bake-wreck-roofs.ts; do not edit. Asset-local Y-up upward faces.\nexport const wreckRoofs: Record<string, { source: string; hash: string; positions: number[]; indices: number[] }> = ' + JSON.stringify(roofs) + ';\n');
console.log(Object.fromEntries(Object.entries(roofs).map(([key, value]) => [key, value.indices.length / 3])));
