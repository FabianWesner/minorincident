import { readFileSync, writeFileSync } from 'node:fs';
import assert from 'node:assert/strict';
import { gunzipSync } from 'node:zlib';
import { provenance } from './probe.ts';
import { loadLevel } from '../../sim-runner/levels.ts';
import { NavGrid } from '../../../src/sim/ai/NavGrid.ts';
import { l4WallSlots } from '../../../src/data/l4Perimeter.ts';
import { PathProbe, ThreatObserver } from '../threat/observer.ts';
const d = JSON.parse(gunzipSync(readFileSync('docs/reports/fix51-r6b/l4-seam-native-snapshot.json.gz')).toString());
const s = d.snapshots.filter(s => s.key === 'phase/war').at(-1);
const world = await loadLevel('L4', 1, undefined, 0, { quality: 'low' });
const native = world.infected.navigation.grid(s.player.transform);
const n = s.navigation;
assert.deepEqual(native.walls, n.walls, 'the replay retains the current unchanged L4 static geometry');
assert.deepEqual(native.ground, n.ground);
const source = new NavGrid(n.ground, n.walls, n.clearance, n.center, native.mask, n.cellSize);
for (const [id, wall] of n.blockers) source.setBlocker(id, wall, true);
const barriers = n.blockers.flatMap(([id, wall]) => {
 const slot = l4WallSlots.find(slot => Math.abs((slot.a.x + slot.b.x)/2-wall.x)<1e-7 && Math.abs((slot.a.z+slot.b.z)/2-wall.z)<1e-7);
 return slot ? [{ id, transform: {x:wall.x,z:wall.z}, health:{current:slot.initialHp}, barricade:{intact:true,slot} }] : [];
});
const paths = new PathProbe(), observer = Object.assign(Object.create(ThreatObserver.prototype), { world:{entities:{iterate:()=>barriers}}, paths, barrierGrids:new WeakMap() });
const before = JSON.parse(readFileSync('docs/reports/fix51-r6b/l4-barrier-centre-before.json', 'utf8'));
assert.equal(s.tick, before.tick);
const revision = source.revision, blocked = [...source.blocked];
const results = before.results.map(record => {
 const entity = s.actors.find(e => e.id === record.entity);
 assert(entity);
 const distance = observer.barrierDistance(source, entity, s.player.transform, record.unchangedLimit);
 assert(Number.isFinite(distance) && distance <= record.unchangedLimit);
 assert.equal(record.oldAccepted, false);
 return { ...record, correctedAccepted: true, correctedDistance: distance };
});
assert(results.length > 0);
assert.equal(source.revision, revision);
assert.deepEqual([...source.blocked], blocked);
writeFileSync('docs/reports/fix51-r6b/l4-barrier-centre-proof.json', JSON.stringify({ ...provenance(), recordedSourceHash: d.sourceHash, tick: s.tick, method: 'Read-only replay of exact recorded native geometry; original observer rejected these11 complete full-body paths; corrected observer accepts the proven segment-centre approach within the same2.5x bound; actual L4 walkable-domain mask retained; original grid unchanged.', results }, null, 2));
world.dispose();
console.log(`PASS: ${results.length} recorded seam-crossing false failures corrected in the actual L4 walkable domain; source grid unchanged.`);
